// Lấy L, M, S tại tháng tuổi (nội suy tuyến tính giữa 2 tháng, đúng như WHO AnthroPlus)
function lmsAt(sex, ageMonths) {
  const table = LMS_BMI_FOR_AGE[sex === "female" ? 2 : 1];
  const raw = ageMonths - WHO_BMI_FIRST_MONTH;
  const i = Math.floor(raw);
  if (i < 0 || i > table.length - 1) return null;
  const a = table[i];
  if (i === table.length - 1) return { l: a[0], m: a[1], s: a[2] };
  const frac = raw - i;
  const b = table[i + 1];
  return {
    l: a[0] + frac * (b[0] - a[0]),
    m: a[1] + frac * (b[1] - a[1]),
    s: a[2] + frac * (b[2] - a[2])
  };
}

// Giá trị nhân trắc tại một mốc z theo LMS: y = M * (1 + L*S*z)^(1/L)
export function valueAtZ(lms, z) {
  if (Math.abs(lms.l) < 1e-9) return lms.m * Math.exp(lms.s * z);
  return lms.m * Math.pow(1 + lms.l * lms.s * z, 1 / lms.l);
}

// z-score thô: z = ((y/M)^L - 1) / (L*S)
export function zFromValue(value, lms) {
  if (Math.abs(lms.l) < 1e-9) return Math.log(value / lms.m) / lms.s;
  return (Math.pow(value / lms.m, lms.l) - 1) / (lms.l * lms.s);
}

// z-score "hiệu chỉnh" của WHO: ngoài ±3SD dùng nội suy tuyến tính theo
// khoảng cách SD2-SD3 (anthro_api_compute_zscore_adjusted). Nhờ vậy kết quả
// trùng khớp 100% với phần mềm WHO AnthroPlus.
export function whoAdjustedZScore(value, lms) {
  const z = zFromValue(value, lms);
  if (z > 3) {
    const sd3 = valueAtZ(lms, 3);
    const sd2 = valueAtZ(lms, 2);
    return 3 + (value - sd3) / (sd3 - sd2);
  }
  if (z < -3) {
    const sd3 = valueAtZ(lms, -3);
    const sd2 = valueAtZ(lms, -2);
    return -3 + (value - sd3) / (sd2 - sd3);
  }
  return z;
}

// Xác suất tích luỹ chuẩn Φ(z) -> bách phân vị (xấp xỉ Abramowitz & Stegun 7.1.26)
export function normalCdf(z) {
  const sign = z < 0 ? -1 : 1;
  const x = Math.abs(z) / Math.SQRT2;
  const t = 1 / (1 + 0.3275911 * x);
  const poly = ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t;
  const erf = 1 - poly * Math.exp(-x * x);
  return 0.5 * (1 + sign * erf);
}

// 5 nhóm của WHO 2007 cho 5-19 tuổi (ngưỡng theo SD, không theo BMI tuyệt đối)
export const WHO_BMI_CATEGORIES = [
  { key: "thin_severe", label: "Gầy nặng", range: "z < -3", color: "#b91c1c" },
  { key: "thin", label: "Gầy", range: "-3 ≤ z < -2", color: "#d97706" },
  { key: "normal", label: "Bình thường", range: "-2 ≤ z ≤ +1", color: "#10b981" },
  { key: "overweight", label: "Thừa cân", range: "+1 < z ≤ +2", color: "#f97316" },
  { key: "obese", label: "Béo phì", range: "z > +2", color: "#dc2626" }
];

export function classifyWhoBmi(z) {
  if (z < -3) return WHO_BMI_CATEGORIES[0];
  if (z < -2) return WHO_BMI_CATEGORIES[1];
  if (z <= 1) return WHO_BMI_CATEGORIES[2];
  if (z <= 2) return WHO_BMI_CATEGORIES[3];
  return WHO_BMI_CATEGORIES[4];
}

// Trả về null nếu tuổi nằm ngoài 10-19 (khi đó dùng ngưỡng người trưởng thành).
export function bmiForAge(bmi, ageYears, gender) {
  if (!(bmi > 0) || !(ageYears > 0)) return null;
  const ageMonths = Math.floor(ageYears * 12);
  if (ageMonths < WHO_BMI_MIN_AGE * 12 || ageMonths > WHO_BMI_MAX_AGE * 12) return null;
  const lms = lmsAt(gender, ageMonths);
  if (!lms) return null;

  const z = whoAdjustedZScore(bmi, lms);
  const category = classifyWhoBmi(z);
  return {
    z: Math.round(z * 100) / 100,
    percentile: Math.round(normalCdf(z) * 1000) / 10,
    medianBmi: Math.round(lms.m * 10) / 10,
    category,
    reference: WHO_BMI_REFERENCE,
    ageMonths
  };
}
